// Relational statement with constant

void main()
{   
    if(10 > 5){
        print("10 > 5");
    }

    if(10 < 5){
        print("10 < 5");
    }

    if(20.1 >= 30.5) {
        print("20.1 >= 30.5");
    }

    if(20.1 <= 30.5) {
        print("20.1 <= 30.5");
    }

    if(10 != 10) {
        print("10 != 10");
    }
}
